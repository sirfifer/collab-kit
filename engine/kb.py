# --------------------------------------------------------------------------- text helpers --

def slugify(text: str, limit: int = 60) -> str:
    t = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().lower()
    t = re.sub(r"[`*_\[\]()'\"]", "", t)
    t = re.sub(r"[^a-z0-9]+", "-", t).strip("-")
    if len(t) > limit:
        t = t[:limit].rsplit("-", 1)[0]
    return t or "section"


def heading_key(title: str) -> str:
    stripped = NUM_PREFIX_RE.sub("", title).strip()
    return slugify(stripped or title)


def clean_title(title: str) -> str:
    return re.sub(r"[*`]", "", title).strip()


def nwords(lines: list[str]) -> int:
    return sum(len(l.split()) for l in lines)


def fmt(n: int) -> str:
    return f"{n:,}"


# ------------------------------------------------------------------------ document model --

@dataclass
class Heading:
    line: int          # 0-based
    level: int
    title: str
    key: str = ""      # unique within document


@dataclass
class Chunk:
    num: int
    start: int         # 0-based inclusive
    end: int           # 0-based exclusive
    title: str
    words: int
    headings: list[Heading] = field(default_factory=list)
    filename: str = ""


@dataclass
class Doc:
    code: str
    title: str
    source: str
    tier: str
    about: str
    chunking: str
    max_words: int
    lines: list[str] = field(default_factory=list)
    headings: list[Heading] = field(default_factory=list)
    chunks: list[Chunk] = field(default_factory=list)
    dirname: str = ""
    fullname: str = ""
    recent: bool = False      # listed under the recent heading in 02-RECENT.md (collections with recent = true)

    @property
    def words(self) -> int:
        return nwords(self.lines)

    def chunk_at(self, line: int) -> Chunk:
        for c in self.chunks:
            if c.start <= line < c.end:
                return c
        return self.chunks[-1]


def parse_headings(lines: list[str]) -> list[Heading]:
    heads, fence = [], None
    for i, line in enumerate(lines):
        m = FENCE_RE.match(line)
        if m:
            tok = m.group(1)
            if fence is None:
                fence = tok
            elif tok[0] == fence[0] and len(tok) >= len(fence) and line.strip() == tok:
                fence = None
            continue
        if fence:
            continue
        m = HEAD_RE.match(line)
        if m:
            heads.append(Heading(i, len(m.group(1)), m.group(2).strip()))
    seen: dict[str, int] = {}
    for h in heads:
        base = heading_key(h.title)
        seen[base] = seen.get(base, 0) + 1
        h.key = base if seen[base] == 1 else f"{base}-{seen[base]}"
    return heads


def split_paragraphs(lines, start, end, max_words):
    """Split [start,end) at blank lines (then at any line) into pieces of <= max_words."""
    out, cur_s, cur_w = [], start, 0
    para_s = start
    i = start
    breaks = [j for j in range(start, end) if not lines[j].strip()] + [end]
    for b in breaks:
        pw = nwords(lines[para_s:b + 1 if b < end else end])
        if cur_w and cur_w + pw > max_words:
            out.append((cur_s, para_s))
            cur_s, cur_w = para_s, 0
        cur_w += pw
        para_s = b + 1
    if cur_s < end:
        out.append((cur_s, end))
    # any single piece still far too large (no blank lines): cut by lines
    final = []
    for s, e in out:
        if nwords(lines[s:e]) <= max_words * 1.5:
            final.append((s, e))
            continue
        cs, cw = s, 0
        for j in range(s, e):
            w = len(lines[j].split())
            if cw and cw + w > max_words:
                final.append((cs, j))
                cs, cw = j, 0
            cw += w
        final.append((cs, e))
    return [p for p in final if p[0] < p[1]]


def split_range(lines, heads, start, end, level, max_words):
    """Cover [start,end) with line ranges of <= max_words, splitting at headings of `level`
    and deeper. Adjacent small pieces are packed together."""
    if nwords(lines[start:end]) <= max_words:
        return [(start, end)]
    subs = [h.line for h in heads if start < h.line < end and h.level == level]
    if not subs:
        deeper = [h for h in heads if start < h.line < end and h.level > level]
        if deeper:
            return split_range(lines, heads, start, end, min(h.level for h in deeper), max_words)
        return split_paragraphs(lines, start, end, max_words)
    bounds = [start] + subs + [end]
    out, cur = [], None
    for s, e in zip(bounds, bounds[1:]):
        if nwords(lines[s:e]) > max_words:
            if cur:
                out.append(cur)
                cur = None
            out.extend(split_range(lines, heads, s, e, level + 1, max_words))
        elif cur and nwords(lines[cur[0]:e]) <= max_words:
            cur = (cur[0], e)
        else:
            if cur:
                out.append(cur)
            cur = (s, e)
    if cur:
        out.append(cur)
    return out


def chunk_sections(doc: Doc) -> list[tuple[int, int, str]]:
    lines, heads = doc.lines, doc.headings
    l2 = [h for h in heads if h.level == 2]
    if not l2:
        return chunk_packed(doc)
    ranges: list[tuple[int, int, str]] = []
    if l2[0].line > 0 and nwords(lines[:l2[0].line]) > 0:
        for s, e in split_range(lines, heads, 0, l2[0].line, 3, doc.max_words):
            ranges.append((s, e, "Introduction"))
    bounds = [h.line for h in l2] + [len(lines)]
    for h, s, e in zip(l2, bounds, bounds[1:]):
        parts = split_range(lines, heads, s, e, 3, doc.max_words)
        for k, (ps, pe) in enumerate(parts, 1):
            title = clean_title(h.title)
            if len(parts) > 1:
                title += f" (part {k} of {len(parts)})"
            ranges.append((ps, pe, title))
    return _fix_intro_titles(doc, ranges)


def _fix_intro_titles(doc, ranges):
    intro = [r for r in ranges if r[2] == "Introduction"]
    if len(intro) > 1:
        out, k = [], 0
        for s, e, t in ranges:
            if t == "Introduction":
                k += 1
                t = f"Introduction (part {k} of {len(intro)})"
            out.append((s, e, t))
        return out
    return ranges


def chunk_packed(doc: Doc) -> list[tuple[int, int, str]]:
    lines, heads = doc.lines, doc.headings
    bounds = sorted({0, *[h.line for h in heads], len(lines)})
    forced = {h.line for h in heads if re.match(r"(?i)prompt\b", h.title)}
    first_forced = min(forced) if forced else None
    blocks = list(zip(bounds, bounds[1:]))
    out, cur = [], None
    for s, e in blocks:
        if s == first_forced and cur:
            out.append(cur)
            cur = None
        if nwords(lines[s:e]) > doc.max_words:
            if cur:
                out.append(cur)
                cur = None
            out.extend(split_paragraphs(lines, s, e, doc.max_words))
        elif cur and nwords(lines[cur[0]:e]) <= doc.max_words:
            cur = (cur[0], e)
        else:
            if cur:
                out.append(cur)
            cur = (s, e)
    if cur:
        out.append(cur)
    titled = []
    for idx, (s, e) in enumerate(out, 1):
        titled.append((s, e, _packed_title(doc, s, e, idx, first_forced)))
    return titled


def _packed_title(doc, s, e, idx, first_forced):
    if idx == 1 and first_forced is not None and e <= first_forced:
        return "Summary and outline"
    skip = re.compile(r"(?i)^(prompt|response|thought process)\b")
    for h in doc.headings:                       # transcripts: title a section by what was asked
        if s <= h.line < e and re.match(r"(?i)prompt\b", h.title):
            for line in doc.lines[h.line + 1:min(e, h.line + 12)]:
                t = re.sub(r"^[#>*\-\s`]+", "", line).strip()
                if sum(1 for w in t.split() if re.search(r"[A-Za-z]{2}", w)) >= 3 and \
                        not re.match(r"\d{1,2}/\d{1,2}/\d{2,4}", t):
                    words = t.split()
                    return "Asked: " + " ".join(words[:10]) + ("…" if len(words) > 10 else "")
    for h in doc.headings:
        if s <= h.line < e and h.level <= 3 and not skip.match(h.title):
            return clean_title(h.title)[:80]
    for line in doc.lines[s:e]:
        t = re.sub(r"^[#>*\-\s`]+|\[\d\d:\d\d:\d\d\]", "", line).strip()
        if len(t.split()) >= 4 and not skip.match(t):
            words = t.split()
            return " ".join(words[:10]) + ("…" if len(words) > 10 else "")
    return f"Part {idx}"


