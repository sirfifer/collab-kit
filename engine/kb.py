    # -- compare / write
    def generated_dirs(self):
        return [self.out / "documents", self.out / "full"]

    def orphans(self) -> list[Path]:
        out = []
        for g in self.generated_dirs():
            if g.exists():
                for p in g.rglob("*"):
                    if p.is_file() and p not in self.files and p.name != ".DS_Store":
                        out.append(p)
        return out

    def stale(self) -> list[Path]:
        s = [p for p, t in self.files.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        return s + self.orphans()

    def write(self) -> tuple[int, int]:
        if self.links:
            return 0, 0
        changed = 0
        for p, t in self.files.items():
            if not p.exists() or p.read_text(encoding="utf-8") != t:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(t, encoding="utf-8")
                changed += 1
        removed = 0
        for p in self.orphans():          # only inside generated dirs
            p.unlink()
            removed += 1
        for g in self.generated_dirs():
            if g.exists():
                for d in sorted((x for x in g.rglob("*") if x.is_dir()), reverse=True):
                    if not any(d.iterdir()):
                        d.rmdir()
        return changed, removed


