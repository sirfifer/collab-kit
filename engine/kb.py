def shell_env(c: dict) -> list[str]:
    """Shell assignments for nightly.sh and launchd/install.sh (eval'd there)."""
    p, m, cu, sc = c["project"], c["mirror"], c["curator"], c["schedule"]
    slug = p["slug"]
    wt, state = cu["worktree"], sc["state_dir"]
    loc, why = mirror_location(c)
    hh, mm = (str(sc["nightly"]).split(":") + ["0"])[:2]
    scalars = {
        "KB_PROJECT": p["name"], "KB_SLUG": slug, "KB_MAIN": p["main_branch"],
        "KB_CONTENT_WORD": p["content_word"], "KB_HUMAN": c["people"]["human"],
        "KB_OUT": c["knowledge"]["out_dir"],
        "KB_REPO_NAME": p["repo"], "KB_PARENT": m["parent"], "KB_START_FILE": m["start_file"],
        "KB_NAMING_ERROR": "; ".join(naming_errors(c)),
        "KB_MIRROR_KIND": m["kind"], "KB_DRIVE_ACCOUNT": m["account"],
        "KB_MIRROR_DIR_DEFAULT": str(loc) if loc else "", "KB_MIRROR_WHY": why,
        "KB_MARKER": m["marker"], "KB_SETTLE_MIN_DEFAULT": str(m["settle_minutes"]),
        "KB_CAPTURES_IN_GIT": {True: "true", False: "false", None: ""}[captures_in_git(c)],
        "KB_CURATOR_BRANCH": cu["branch"], "KB_CURATOR_WT_DEFAULT": os.path.expanduser(wt),
        "KB_AI_TIMEOUT_DEFAULT": str(cu["timeout"]), "KB_AI_MODEL_DEFAULT": cu["model"],
        "KB_CLAUDE_DEFAULT": cu["claude"],
        "KB_STATE_DEFAULT": os.path.expanduser(state), "KB_LABEL_PREFIX": sc["label_prefix"],
        "KB_NIGHTLY_HOUR": str(int(hh)), "KB_NIGHTLY_MINUTE": str(int(mm)),
        "KB_RETURNS_SECONDS": str(int(sc["returns_every_minutes"]) * 60),
    }
    arrays = {"KB_AUTHOR_PATHS": p["author_paths"], "KB_ACCOUNT_ALIASES": m["account_aliases"],
              "KB_REFUSE": m["refuse"]}
    out = [f"{k}={shlex.quote(str(v))}" for k, v in scalars.items()]
    out += [f"{k}=({' '.join(shlex.quote(str(x)) for x in v)})" for k, v in arrays.items()]
    return out


