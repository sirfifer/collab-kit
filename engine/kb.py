# ------------------------------------------------------- naming, the parent, the returns --
# Every project's knowledge folder sits inside one parent folder ([mirror].parent) and has exactly
# the repository's name. File names repeat across projects (CLAUDE.md, 01-INDEX.md, W-001,
# _returns/), so conversations find a project by its folder, scope every search to that folder's
# id, and every return names its project; a return that names another project is refused.

def naming_errors(c: dict) -> list[str]:
    p, m = c["project"], c["mirror"]
    errs = []
    if p["repo_declared"] and p["repo_declared"] != p["repo"]:
        errs.append(f"[project].repo is {p['repo_declared']!r} but the repository is {p['repo']!r} "
                    f"({p['repo_source']}); remove the setting or fix the name")
    if m["kind"] == "none":
        return errs
    if m["folder"] != p["repo"]:
        errs.append(f"[mirror].folder is {m['folder']!r} but the repository is {p['repo']!r}: a project's "
                    "knowledge folder has exactly its repository's name (remove [mirror].folder to use it)")
    par = str(m["parent"])
    if not par.strip() or "/" in par or par.strip() != par:
        errs.append(f"[mirror].parent {par!r} must be one folder name (no slashes, no outer spaces)")
    if m["kind"] == "folder" and not m["root"]:
        errs.append("[mirror].kind is folder but [mirror].root is empty (the folder that holds the parent)")
    if m.get("path"):
        errs.append("[mirror].path is no longer used: set [mirror].root to the folder that holds the parent")
    return errs


def naming_warnings(c: dict) -> list[str]:
    p = c["project"]
    if p["repo_source"] == "origin remote" and p["repo_local"] != p["repo"]:
        return [f"the local folder is {p['repo_local']!r} but the remote repository is {p['repo']!r}; "
                "rename the folder to match"]
    return []


def drive_dirs(m: dict) -> list[Path]:
    accts = [a for a in [m["account"], *m["account_aliases"]] if a]
    return [Path.home() / "Library" / "CloudStorage" / f"GoogleDrive-{a}" for a in accts]


def mirror_location(c: dict) -> tuple[Path | None, str]:
    """(the project's mirror folder, or None and why not). Never 'whichever Drive is mounted'."""
    m, p = c["mirror"], c["project"]
    if m["kind"] == "none":
        return None, "none"
    if m["kind"] not in ("google-drive", "folder"):
        return None, f"unknown [mirror].kind {m['kind']!r} (google-drive | folder | none)"
    if m["root"]:
        root = Path(os.path.expanduser(m["root"]))
    elif m["kind"] == "folder":
        return None, "[mirror].kind is folder but [mirror].root is empty"
    elif not m["account"]:
        return None, "[mirror].account is empty: name the Google account explicitly in tools/kb/config.toml"
    else:
        found = next((d for d in drive_dirs(m) if d.is_dir()), None)
        if not found:
            return None, (f"Google Drive for {m['account']} is not mounted on this machine. Add that account "
                          "in Google Drive for desktop, or set [mirror].root")
        root = found / "My Drive"
    return root / m["parent"] / m["folder"], ""


PROJECT_LINE_RE = re.compile(r"^[\s*_>-]*project[\s*_]*:\s*(.+?)\s*$", re.I | re.M)


def check_return(path: Path, repo: str) -> str | None:
    """None when the return is for this project; otherwise why it is refused."""
    if path.suffix.lower() in (".gdoc", ".gsheet", ".gslides"):
        return ("a Google Docs file: its text cannot be read here, so its Project line cannot be checked "
                "(send it again as a plain text file)")
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        return f"unreadable ({e})"
    mm = PROJECT_LINE_RE.search("\n".join(text.splitlines()[:20]))
    if not mm:
        return f"no Project line (a return starts with \"Project: {repo}\")"
    named = mm[1].strip().strip("`'\"*_").strip()
    if named.lower() != repo.lower():
        return f"it names the project {named!r}, not {repo!r}: it belongs in that project's _returns folder"
    return None


