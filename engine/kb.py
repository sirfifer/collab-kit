def tokens(s: str) -> list[str]:
    return [t for t in re.findall(r"[a-z0-9]+", s.lower()) if t not in STOP and len(t) > 1]


def cmd_find(args):
    q = " ".join(args.words)
    qt = set(tokens(q))
    qphrase = q.lower().strip()
    if not qt:
        print("find: give some words to look for")
        return 2
    b = Build()
    results = []

    def score(text: str, weight: float) -> float:
        tt = tokens(text)
        if not tt:
            return 0.0
        hit = len(qt & set(tt))
        s = weight * hit / len(qt)
        if qphrase and qphrase in text.lower():
            s += weight
        return s

    for cid, e in b.concepts.items():
        s = max(score(e.title, 3), *(score(a, 2.5) for a in e.meta.get("aliases", [""]))) + score(
            e.meta.get("summary", ""), 1.2) + score(e.body, 0.4)
        if s > 0.3:
            secs = "; ".join(describe(r) for r in b.resolved.get(("concept", cid), [])[:3])
            results.append((s, f"concept  {e.title}  →  {rel(e.path)}" + (f"\n           read: {secs}" if secs else "")))
    for kid, k in b.kbs.items():
        s = max(score(k.meta.get("question", ""), 3), *(score(a, 2.5) for a in k.meta.get("also_asked", [""]))) \
            + score(k.meta.get("short_answer", ""), 1.0)
        if s > 0.3:
            results.append((s, f"answer   {kid}: {k.meta.get('question')}  →  {rel(k.path)}"))
    for d in b.docs:
        tier_w = float(tier(d.tier).get("weight", 1.0))
        for h in d.headings:
            s = score(h.title, 2.0 * tier_w)
            if s > 0.5:
                c = d.chunk_at(h.line)
                results.append((s, f"heading  {d.code} · {clean_title(h.title)}  →  {c.filename} "
                                   f"(ref {d.code}#{h.key}, source lines from {h.line + 1})"))
        for c in d.chunks:
            body = "\n".join(d.lines[c.start:c.end]).lower()
            hits = sum(body.count(t) for t in qt)
            covered = sum(1 for t in qt if t in body)
            if covered == len(qt) and hits:
                s = (0.8 + min(hits, 40) / 40) * tier_w + (1.0 if qphrase in body else 0)
                results.append((s, f"text     {d.code} · {c.title}  →  {c.filename} "
                                   f"(lines {c.start + 1}-{c.end}, {hits} hits)"))
    results.sort(key=lambda x: -x[0])
    if not results:
        print(f"find: nothing for {q!r}. Try other words, or grep the full/ folder.")
        return 1
    for s, line in results[: args.limit]:
        print(f"{s:5.2f}  {line}")
    return 0


