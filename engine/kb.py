def repo_identity(root: Path) -> tuple[str, str, str]:
    """(repository name, where it came from, the main checkout's folder name).

    The name is the origin remote's repository name when there is one, else the folder name of
    the main checkout (a worktree's own folder name never counts: worktrees are named per task)."""
    import subprocess

    def git(*a: str) -> str:
        try:
            r = subprocess.run(["git", "-C", str(root), *a], capture_output=True, text=True, timeout=10)
            return r.stdout.strip() if r.returncode == 0 else ""
        except (OSError, subprocess.SubprocessError):
            return ""

    top = git("rev-parse", "--show-toplevel")
    if not top or Path(top).resolve() != root.resolve():
        return root.resolve().name, "folder name (not a git repository)", root.resolve().name
    common = git("rev-parse", "--path-format=absolute", "--git-common-dir")
    local = Path(common).parent.name if common else root.resolve().name
    url = git("remote", "get-url", "origin")
    if url:
        name = re.sub(r"\.git$", "", re.split(r"[/:]", url.rstrip("/"))[-1])
        if name:
            return name, "origin remote", local
    return local, "main checkout folder", local


